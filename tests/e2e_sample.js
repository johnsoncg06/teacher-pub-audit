// 端對端：以內建範例資料走完流程（不含任何真實資料）。node tests/e2e_sample.js
const fs = require('fs'); const { chromium, url, check, done } = require('./helpers.js');
(async () => {
  const b = await chromium.launch(); const ctx = await b.newContext({ acceptDownloads: true, viewport: { width: 1360, height: 900 } }); const p = await ctx.newPage();
  const errs = []; p.on('pageerror', e => errs.push(e.message)); let dialogs = []; p.on('dialog', async d => { dialogs.push(d.message()); await d.accept(); });
  await p.goto(url()); await p.waitForTimeout(500);
  console.log('範例資料');
  await p.click('[data-act="sample"]'); await p.waitForTimeout(400);
  const st = await p.evaluate(() => ({ t: S.teachers.length, rec: REC.length, rows: ROWS.length, tiers: [0, 1, 2, 3, 4].map(x => ROWS.filter(r => r.tier === x).length), todo: todoCount() }));
  check('8 位教師、36 篇、44 列', st.t === 8 && st.rec === 36 && st.rows === 44, st);
  check('比對分級 35/3/3/3/0', JSON.stringify(st.tiers) === '[35,3,3,3,0]', st.tiers);
  check('待審核 6 筆', st.todo === 6, st.todo);
  console.log('報表（預設規則）');
  await p.evaluate(() => go(7)); await p.waitForTimeout(300);
  const stats = await p.$$eval('.stats .stat b', e => e.map(x => x.textContent));
  check('採計 31 篇、8／8 位、Q1 17、Q1+Q2 38', JSON.stringify(stats) === JSON.stringify(['31', '8／8', '17', '38']), stats);
  check('報表有「計算條件與資料來源」', (await p.textContent('.conds')).includes('尚待審核 6 筆'));
  check('範例資料警語', (await p.textContent('#main')).includes('範例資料'));
  console.log('審核快捷鍵與批次');
  await p.evaluate(() => go(6)); await p.waitForTimeout(300);
  await p.keyboard.press('y'); await p.waitForTimeout(150); await p.keyboard.press('n'); await p.waitForTimeout(150);
  let d = await p.evaluate(() => ({ n: Object.keys(S.decisions).length, todo: todoCount() }));
  check('Y、N 各標記一筆', d.n === 2 && d.todo === 4, d);
  await p.click('[data-mode="decided"]'); await p.waitForTimeout(200); await p.keyboard.press('u'); await p.waitForTimeout(150);
  check('已審核列表按 U 取消標記', (await p.evaluate(() => Object.keys(S.decisions).length)) === 1);
  await p.click('[data-mode="todo"]'); await p.waitForTimeout(200);
  const before = await p.evaluate(() => todoCount()); await p.click('[data-bulk="yes"]'); await p.waitForTimeout(300);
  check('批次標記後待審核歸零', (await p.evaluate(() => todoCount())) === 0 && dialogs.some(m => m.includes(String(before))), { before, dialogs });
  console.log('匯出');
  const dl = async sel => { const [x] = await Promise.all([p.waitForEvent('download'), p.click(sel)]); const f = '/tmp/_e2e_' + Date.now(); await x.saveAs(f); return fs.readFileSync(f, 'utf8'); };
  await p.evaluate(() => go(7)); await p.waitForTimeout(300);
  const conds = await dl('[data-act="expConds"]'); check('計算條件含單位與審核統計', conds.includes('單位：示範大學') && conds.includes('尚待審核 0 筆'), conds.slice(0, 200));
  const chk = await dl('[data-act="expCheck"]').then(t => t.split('\n').filter(Boolean)); check('抽查表有標頭與 44 列', chk.length === 45 && chk[0].includes('查核：系統判定是否正確'), chk.length);
  const sum = await dl('[data-act="expSum"]'); check('彙總表可匯出', sum.split('\n').length > 8);
  console.log('語言切換');
  await p.selectOption('#langSel', 'en'); await p.waitForTimeout(300);
  check('英文標題', (await p.textContent('h1')).includes('Publication Statistics'));
  check('非中文時顯示譯文免責聲明', await p.evaluate(() => getComputedStyle(document.querySelector('#discSide')).display) === 'block');
  await p.selectOption('#langSel', 'zh-TW'); await p.waitForTimeout(300);
  check('切回繁中免責聲明隱藏', await p.evaluate(() => getComputedStyle(document.querySelector('#discSide')).display) === 'none');
  check('無頁面錯誤', errs.length === 0, errs);
  await b.close(); done();
})();
